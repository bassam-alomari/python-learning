# Syntax => [Variable Name] [Assignment Operator] [value]
#
# Name Convention and Rules
# [1] Can Start With (a-z A-Z) Or Underscore
# [2] You Cannot With Num Or Special Characters
# [3] Can Include (0-9) Or Underscore
# [4] Cannot Include Special Characters
# [5] Name is Not Like name [ Case Sensitive ] 
# -------------------------------------------------------
name = "Bassam Alomari" # Single Word => Normal
myName = "Bassam Alomari" # Two Words => camelCase
my_name = "Bassam Alomari" # Two Words => snake_case

print(name)
print(myName)
print(my_name)