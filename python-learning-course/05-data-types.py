# ============================================================
# WHAT IS DATA?
# ============================================================
# In any application, you have two things:
# [1] The CODE (what you write)
# [2] The DATA (what the code works with)
#
# Example: A school management system
# - Students (names, grades, ages)
# - Teachers (names, subjects, salaries)
# - Classes (room numbers, schedules)
# - Events (dates, descriptions)
#
# ALL of this is DATA.

# ============================================================
# WHY DO WE NEED DATA TYPES?
# ============================================================
# Data comes in different forms:
# - A name is TEXT -> "Bassam"
# - An age is a NUMBER -> 21
# - A grade is a NUMBER -> 95.5
# - Is a student active? -> True or False
#
# Each type needs to be handled differently.
# That is why Python has DIFFERENT DATA TYPES.

# ============================================================
# MAIN DATA TYPES IN PYTHON
# ============================================================
# [1] Numbers
#     - Integer (int): whole numbers -> 1, 42, -10
#     - Float: decimal numbers -> 3.14, -0.5, 99.9
#
# [2] Strings (str)
#     - Text data -> "Hello", "Bassam", "Python"
#     - Anything inside quotes is a string
#
# [3] Booleans (bool)
#     - Only two values: True or False
#     - Used for conditions and decisions

# ============================================================
# VARIABLES (Preview - detailed in next lesson)
# ============================================================
# Variables are like LABELS or BOXES that store data
# They let you access data easily in your code
#
# Important: A variable does NOT contain the data directly
# It is a REFERENCE (pointer) to where the data lives
# in the computer's memory
#
# Think of it like:
# - Data = a book on a shelf
# - Variable = a sticky note on the shelf saying "Book is here"

# ============================================================
# HOW DATA IS USED IN CODE
# ============================================================
# Example 1: Register a new student
# name = "Ahmad"
# age = 20
# grade = 95
#
# Example 2: Calculate salary
# salary_per_day = 50
# days_worked = 22
# total_salary = salary_per_day * days_worked

# ============================================================
# KEY TAKEAWAYS
# ============================================================
# [1] Data = information your program works with
# [2] Data Types tell Python HOW to handle the data
# [3] Main types: Numbers (int, float), Strings, Booleans
# [4] Variables store REFERENCES to data in memory
# [5] You MUST know data types to write correct code

