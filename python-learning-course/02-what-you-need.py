# WHAT YOU NEED TO START LEARNING PYTHON
# ============================================================

# [1] Text Editor or IDE
#    - IDE = Integrated Development Environment
#    - Recommended: VS Code (free, made by Microsoft)
#    - Alternative: PyCharm (JetBrains)
#    - If you are a university student, JetBrains gives
#      you Professional version FREE for 1 year with
#      your university email

# [2] Download Python
#    - Go to python.org/downloads
#    - Download the latest version (Python 3.x)
#    - During installation on Windows:
#      IMPORTANT: Check "Add Python to PATH"
#      This lets you run Python from anywhere on your computer

# [3] Python Extension for VS Code
#    - Install the official Python extension in VS Code
#    - It gives you autocomplete, linting, debugging
#    - Downloaded millions of times - very reliable

# [4] Learn Command Line
#    - You MUST learn the terminal/command line
#    - It is essential for programming
#    - Learn basic commands: cd, ls/dir, mkdir, etc.

# [5] Download Cmder (Optional)
#    - Cmder is a better terminal for Windows
#    - More features than the default Command Prompt
#    - Switch between them when needed

# [6] Basic Programming Knowledge
#    - Helpful but NOT required
#    - The course explains things as it goes
#    - If you know English, read programming articles

# [7] Python Version
#    - Always use Python 3 (the latest version)
#    - Python 2 is old and no longer supported
#    - All modern libraries work with Python 3

# [8] Path Knowledge
#    - Python has many career paths:
#      Web Development, AI, Cyber Security, Data Science
#    - Each path requires different additional tools
#    - Pick one path and focus on it

