# ============================================================
# KEY TERMS
# ============================================================
# Interpreter vs Compiler:
# - Interpreter: Runs code line by line (Python)
# - Compiler: Converts all code at once before running (C, C++)
#
# Garbage Collection:
# - Python automatically cleans up memory you no longer need
# - You don't have to worry about memory management
#
# OOP (Object-Oriented Programming):
# - A way to organize code using "objects"
# - We will learn this in detail later in the course
#
# Modules & Packages:
# - Pre-made code that you can import and use
# - Like toolboxes - each one has different tools

